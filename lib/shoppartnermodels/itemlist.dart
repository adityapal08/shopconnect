class Product {
  final String id;
  final String productName;
  final int quantity;
  final String unit;
  final double sellingPrice;
  final double purchasePrice;

  Product({
    required this.id,
    required this.productName,
    required this.quantity,
    required this.unit,
    required this.sellingPrice,
    required this.purchasePrice,
  });
}
